#!/usr/bin/env node
/**
 * Build an offline, nested iframe portal from all eligible HTML files in a directory.
 * Does not execute/modify the source pages; only writes a generated portal index.
 */
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const ownDir=path.dirname(fileURLToPath(import.meta.url));
const packageRoot=path.resolve(ownDir,"..");
const AUTO_MARK="<!-- GEN-UI:AUTOGENERATED-IFRAME-PORTAL v1 -->";
const blockedDirs=new Set([".git","node_modules",".next",".nuxt","dist",".cache","coverage"]);
const htmlExt=/\.html?$/i;
const collator=new Intl.Collator("zh-CN",{numeric:true,sensitivity:"base"});
function fail(message){throw Error(message);}
function argsOf(args){
  const opts={};
  for(let i=0;i<args.length;i++){
    if(args[i]==="--help")return {help:true};
    const key=args[i];
    if(!["--dir","--output","--title"].includes(key)||!args[i+1])fail("用法：node scripts/build-html-portal.mjs --dir 目录 [--output 目录内HTML路径] [--title 标题]");
    if(key in opts)fail("参数重复："+key);
    opts[key]=args[++i];
  }
  if(!opts["--dir"])fail("必须指定 --dir 目录");
  return opts;
}
function safeText(s,max=65){
  return s.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,"")
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi,"")
    .replace(/<[^>]+>/g," ").replace(/&(?:amp|lt|gt|quot|apos|nbsp);|&#(?:x[0-9a-f]+|\d+);/gi,e=>{
      const vals={amp:"&",lt:"<",gt:">",quot:'"',apos:"'",nbsp:" "};
      const name=e.slice(1,-1).toLowerCase();
      if(vals[name])return vals[name];
      if(name[0]==="#"){const n=name[1]==="x"?parseInt(name.slice(2),16):Number(name.slice(1));return Number.isInteger(n)&&n>0&&n<=0x10ffff?String.fromCodePoint(n):" ";}
      return e;
    }).replace(/\s+/g," ").trim().slice(0,max);
}
function makeHref(root,file){
  const rel=path.relative(root,file);
  return rel.split(path.sep).map(encodeURIComponent).join("/");
}
function inspectPage(root,file){
  // Inspect a bounded prefix: large self-contained reports remain indexed in full.
  const fd=fs.openSync(file,"r");
  let source;
  try{
    const buffer=Buffer.alloc(Math.min(fs.statSync(file).size,512*1024));
    const bytes=fs.readSync(fd,buffer,0,buffer.length,0);
    source=buffer.subarray(0,bytes).toString("utf8");
  }finally{fs.closeSync(fd)}
  if(source.startsWith(AUTO_MARK))return null;
  const h1=source.match(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i);
  const title=source.match(/<title\b[^>]*>([\s\S]*?)<\/title>/i);
  const basename=path.basename(file,path.extname(file));
  const pageTitle=safeText(h1?.[1]||title?.[1]||basename)||basename;
  const headings=[],seen=new Set();
  for(const match of source.matchAll(/<h2\b([^>]*)>([\s\S]*?)<\/h2>/gi)){
    const id=match[1].match(/\bid\s*=\s*(?:"([^"]+)"|'([^']+)')/i);
    if(!id)continue;
    const key=id[1]??id[2];
    if(!key||seen.has(key))continue;
    const text=safeText(match[2],50);
    if(text){seen.add(key);headings.push({id:key,title:text});}
    if(headings.length>=8)break;
  }
  return {title:pageTitle,href:makeHref(root,file),sections:headings,parts:path.relative(root,file).split(path.sep)};
}
export function collectPages(root,output){
  const list=[],visited=new Set();
  function walk(dir,depth){
    if(depth>12)fail("目录层级超过 12 级，停止扫描");
    const real=fs.realpathSync(dir);
    if(visited.has(real))return;
    visited.add(real);
    for(const entry of fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>collator.compare(a.name,b.name))){
      const full=path.join(dir,entry.name);
      if(entry.isSymbolicLink())continue;
      if(entry.isDirectory()){
        if(entry.name.startsWith(".")||blockedDirs.has(entry.name))continue;
        walk(full,depth+1);
        continue;
      }
      if(!entry.isFile()||!htmlExt.test(entry.name)||full===output)continue;
      const page=inspectPage(root,full);
      // Skip prior generated portals to avoid recursively indexing an index.
      if(!page)continue;
      list.push(page);
      if(list.length>500)fail("HTML 文件超过 500 个，请按业务目录拆分");
    }
  }
  walk(root,0);
  return list;
}
function inside(root,target){
  const rel=path.relative(root,target);
  return rel!==""&&!rel.startsWith(".."+path.sep)&&rel!==".."&&!path.isAbsolute(rel);
}
export function buildPortal({dir,output,title}){
  if(!dir)fail("未指定目录");
  const root=fs.realpathSync(path.resolve(dir));
  if(!fs.statSync(root).isDirectory())fail("输入不是目录");
  const target=path.resolve(output??path.join(root,"index.html"));
  if(!htmlExt.test(target)||!inside(root,target))fail("输出必须是指定目录内的 HTML 文件");
  const rel=path.relative(root,target).split(path.sep);
  if(rel.some(part=>part.startsWith(".")||blockedDirs.has(part)))fail("输出位置不能位于隐藏或依赖目录");
  // Existing output ancestors may be symlinks even if the path looks nested.
  let ancestor=root;
  for(const part of rel.slice(0,-1)){
    ancestor=path.join(ancestor,part);
    if(fs.existsSync(ancestor)&&fs.lstatSync(ancestor).isSymbolicLink())fail("输出目录包含符号链接，拒绝越界");
  }
  if(fs.existsSync(target)){
    if(fs.lstatSync(target).isSymbolicLink()||!fs.statSync(target).isFile())fail("拒绝覆盖符号链接或非普通文件");
    const original=fs.readFileSync(target,"utf8");
    if(!original.startsWith(AUTO_MARK))fail("目标文件已存在且不是 GEN-UI 自动生成入口；拒绝覆盖："+target);
  }
  const pages=collectPages(root,target);
  if(!pages.length)fail("指定目录中没有可集成的 HTML 文件");
  const css=fs.readFileSync(path.join(packageRoot,"assets/portal-shell.css"),"utf8");
  const js=fs.readFileSync(path.join(packageRoot,"assets/portal-shell.js"),"utf8");
  // Keep generated portals self-contained even when the target directory is elsewhere.
  const brandMark=fs.readFileSync(path.join(packageRoot,"assets/icons/gen-ui-mark.svg"),"utf8").trim();
  const inlineMark=brandMark.replace(/ role="img" aria-labelledby="title"/,' aria-hidden="true" focusable="false"')
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/,"");
  const favicon="data:image/svg+xml;base64,"+Buffer.from(brandMark,"utf8").toString("base64");
  const prefix=path.relative(path.dirname(target),root).split(path.sep).map(x=>encodeURIComponent(x)).join("/");
  // Output may be in a nested directory; keep links rooted at the scanned directory.
  const manifest={title:safeText(title||path.basename(root),70)||"报告目录",prefix,sourceCount:pages.length,pages:pages.map((p,i)=>({id:"p"+(i+1),title:p.title,href:p.href,sections:p.sections,parts:p.parts}))};
  const escaped=JSON.stringify(manifest).replace(/</g,"\\u003c").replace(/>/g,"\\u003e").replace(/&/g,"\\u0026").replace(/\u2028/g,"\\u2028").replace(/\u2029/g,"\\u2029");
  const titleText=manifest.title.replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
  // Double-clicked file:// portals need same-origin for local CSS; scripts remain disabled.
  // When served over loopback HTTP, portal-shell.js switches to an opaque-origin script sandbox.
  const frameSandbox=' sandbox="allow-same-origin"';
  const html=[AUTO_MARK,"<!doctype html>",'<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
    "<title>"+titleText+" · GEN-UI</title>",
    '<link rel="icon" type="image/svg+xml" href="'+favicon+'">',
    "<style>"+css.replace(/<\/style/gi,"<\\/style")+"</style></head><body>",
    '<a class="skip-link" href="#page-frame">跳转到页面内容</a>',
    '<div class="portal" id="portal">',
    '<aside class="rail" id="rail" aria-label="页面目录"><div class="rail-head"><span class="mark" aria-hidden="true">'+inlineMark+'</span><span class="rail-name">GEN-UI</span><button class="icon-button rail-close" id="collapse" type="button" aria-expanded="true" aria-controls="page-nav" title="折叠目录">‹<span class="sr-only">折叠目录</span></button></div><nav id="page-nav" aria-label="页面层级导航"></nav><div class="rail-foot"><span class="rail-foot-label"><span class="rail-foot-mark" aria-hidden="true">'+inlineMark+'</span><span class="rail-foot-text">本地多页面目录</span></span><span class="rail-count" id="page-count"></span></div></aside>',
    '<div class="mobile-backdrop" id="backdrop" hidden></div>',
    '<div class="workspace"><header class="workspace-header"><button class="icon-button menu-button" type="button" id="open-nav" aria-controls="page-nav" aria-expanded="false" aria-label="打开目录">☰</button><span class="workspace-brand-mark" aria-hidden="true">'+inlineMark+'</span><div class="workspace-titles"><p class="workspace-overline" id="breadcrumb"></p><h1 id="active-title" class="sr-only">页面目录</h1></div><a id="open-external" class="open-new" target="_blank" rel="noopener noreferrer" href="#" aria-label="在新标签页打开当前页面">新标签页打开 <span aria-hidden="true">↗</span></a><span class="preview-mode" id="preview-mode"></span></header>',
    '<div class="frame-area"><iframe id="page-frame" title="内容页面" loading="eager" referrerpolicy="no-referrer"'+frameSandbox+' src="about:blank"></iframe><p class="frame-status" id="frame-status" role="status" aria-live="polite"></p></div>',
    '</div></div>',
    '<script type="application/json" id="page-manifest">'+escaped+"</script>",
    "<script>"+js.replace(/<\/script/gi,"<\\/script")+"</script></body></html>",""].join("\n");
  fs.mkdirSync(path.dirname(target),{recursive:true});
  const temporary=target+".gen-ui-tmp";
  if(fs.existsSync(temporary))fail("临时输出已存在，请检查后再运行");
  try{fs.writeFileSync(temporary,html,{encoding:"utf8",flag:"wx"});fs.renameSync(temporary,target)}
  finally{if(fs.existsSync(temporary))fs.rmSync(temporary)}
  return {output:target,mode:"protocol-aware-sandbox",sourceCount:pages.length,groupCount:new Set(pages.map(p=>p.parts.slice(0,-1).join("/"))).size,pages:pages.map(p=>p.href)};
}
const direct=process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url);
if(direct){
 try{const opts=argsOf(process.argv.slice(2));if(opts.help){console.log("用法：node scripts/build-html-portal.mjs --dir <目录> [--output <目录内HTML路径>] [--title <显示标题>]");}
 else console.log(JSON.stringify(buildPortal({dir:opts["--dir"],output:opts["--output"],title:opts["--title"]}),null,2));}
 catch(error){console.error("目录集成失败："+error.message);process.exitCode=1}
}