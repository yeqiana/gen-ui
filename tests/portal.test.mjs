test("本机 HTTP 静态预览加载 CSS/JS，拒绝写入与隐藏文件",async()=>{
 const dir=tempDir();
 try{
  fs.writeFileSync(path.join(dir,"index.html"),html("本地入口"));
  fs.writeFileSync(path.join(dir,"styles.css"),"body{font-size:14px}");
  fs.writeFileSync(path.join(dir,"client.js"),"console.log('fixture')");
  fs.writeFileSync(path.join(dir,".private"),"do not serve");
  const {server,url}=await startPortalServer({dir,port:0});
  try{
   const page=await fetch(url);assert.equal(page.status,200);
   const css=await fetch(url.replace("index.html","styles.css"));
   assert.equal(css.status,200);assert.match(css.headers.get("content-type"),/text\/css/);
   const js=await fetch(url.replace("index.html","client.js"));
   assert.equal(js.status,200);assert.match(js.headers.get("content-type"),/javascript/);
   assert.equal((await fetch(url.replace("index.html",".private"))).status,403);
   assert.equal((await fetch(url,{method:"POST"})).status,405);
  }finally{await new Promise(resolve=>server.close(resolve))}
 }finally{fs.rmSync(dir,{recursive:true,force:true})}
});

